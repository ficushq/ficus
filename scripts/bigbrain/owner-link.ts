import { isAbsolute, resolve } from 'node:path'
import { z } from 'zod'
import {
  managedBigbrainInviteWindowSchema,
  managedBigbrainInviteWindowStatus,
  managedBigbrainOwnerSchema,
} from '@ficus/shared/managed-bigbrain'
import { readBoundedControlBytes } from './control-input'

const inputSchema = z
  .object({
    membersPath: z
      .string()
      .min(1)
      .max(4096)
      .refine((v) => isAbsolute(v) && resolve(v) === v && !/\p{Cc}/u.test(v)),
    handle: managedBigbrainOwnerSchema.shape.handle,
    issuedAt: z.string(),
    expiresAt: z.string(),
  })
  .strict()
export type NativeAppLinkIssuer = (store: string, handle: string, now: Date) => { secret: string; expires: string }
/** Internal policy adapter, run as the isolated vault UID, never a privileged general API.
 * The root controller authenticates/authorizes the owner and manages durable replay receipts.
 * The only upstream export called here is createAppLink; no token, credential or network API.
 */
export function issueOwnerAppLink(
  input: unknown,
  issue: NativeAppLinkIssuer,
  now = Date.now()
): { secret: string; expiresAt: string } {
  const parsed = inputSchema.safeParse(input)
  if (!parsed.success) throw new Error('invalid_request')
  const { membersPath, handle, issuedAt, expiresAt } = parsed.data
  const window = { issuedAt, expiresAt }
  if (!managedBigbrainInviteWindowSchema.safeParse(window).success) throw new Error('invalid_request')
  const status = managedBigbrainInviteWindowStatus(window, now)
  if (status !== 'current')
    throw new Error(status === 'expired' ? 'invite_expired' : status === 'not_yet_valid' ? 'busy' : 'invalid_request')
  const result = issue(membersPath, handle, new Date(issuedAt))
  if (!/^[a-zA-Z0-9_-]{43}$/.test(result.secret) || Date.parse(result.expires) !== Date.parse(expiresAt))
    throw new Error('upstream_protocol')
  // Return the actual upstream value, not a separate computed expiry or an advertised min().
  return { secret: result.secret, expiresAt: result.expires }
}

/** Compiled entrypoint is generated by the fixed-pin artifact builder. No environment policy inputs. */
export async function ownerLinkMain(issue: NativeAppLinkIssuer): Promise<void> {
  try {
    if (process.argv.length !== 2) throw new Error('invalid_request')
    const bytes = await readBoundedControlBytes(Bun.stdin.stream())
    const input: unknown = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes))
    console.log(JSON.stringify(issueOwnerAppLink(input, issue)))
  } catch {
    console.error('Managed BigBrain owner link unavailable')
    process.exitCode = 1
  }
}
