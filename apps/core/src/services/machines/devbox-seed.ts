/**
 * Per-box devbox comfort-set seeding.
 *
 * The k8s sandbox IMAGE baked a "comfort set" of ergonomic CLI tools directly
 * into the box:
 *  - the `agent` stage installed a LIGHT set (node/python + ripgrep/fd/tree/less/
 *    gh/tmux/procps) into the GLOBAL nix profile, on PATH the instant the pod
 *    started (see packages/k8s-sandbox/Dockerfile `agent` stage);
 *  - the `squad` stage baked a HEAVIER devbox toolchain (adds bun/jq/gnumake/gcc/
 *    diffutils/patch/perl) from packages/k8s-sandbox/sandbox/devbox.json.
 *
 * A VM box runs on bare Ubuntu with no such image, so its shells lack the comfort
 * set until we seed one. This module materializes a per-user `devbox` at the
 * box's `FICUS_DEVBOX_DIR` (`~/.tau/devbox`, see packages/k8s-sandbox/src/paths.ts)
 * and runs `devbox install` — AS THE BOX USER, because the sandbox-server executes
 * every `/write` and `/bash` as that user (never root), and the box user owns
 * `~/.tau`.
 *
 * ## Idempotency (the slice-2 sync-on-every-ensure lesson)
 * `devbox install` is slow (minutes). We must NOT pay that on every ensure, so we
 * hash the intended `devbox.json` content and, after a SUCCESSFUL install, record
 * that hash in `~/.tau/devbox/.seeded`. A later ensure whose intended content
 * hashes to the same marker SKIPS the install entirely; a CHANGED comfort set
 * (different hash) forces a fresh install. The marker is written ONLY after a
 * successful install, so a failed install re-attempts on the next ensure.
 *
 * ## Failure semantics (NON-fatal — the caller's contract)
 * Unlike file-sync (fatal: a box missing its CLI/skills/identity is broken), a box
 * without the comfort set still works with a DEGRADED shell (no `rg`/`fd`/etc.).
 * `seedBoxDevbox` therefore THROWS on failure so the caller can decide; the
 * VmSandboxManager wraps the call in a try/catch, logs WARN, and lets the ensure
 * proceed.
 *
 * ## devbox.lock cache (the 48s Nixhub-resolve lesson)
 * Most comfort-set packages use `@latest`, and a brand-new box starts with
 * no `devbox.lock`, so `devbox install` resolves every package against Jetify's
 * Nixhub API over the network — 48s+ measured live, even with a fully warm local
 * `/nix/store` (see jetify-com/devbox `internal/lock/lockfile.go`'s `File.Resolve`:
 * it returns the existing lock entry's `Resolved` value without ever calling
 * `FetchResolvedPackage` — the Nixhub-backed resolver — when one is already
 * present). We cache the devbox.lock generated by the FIRST successful install of
 * a given comfort set (keyed by {@link computeDevboxSeedHash}, the sha256 prefix
 * of the pristine `devbox.json`) and seed it into every later box's devbox dir
 * BEFORE running `devbox install`, so `devbox` resolves from the local lock
 * instead of the network. The cache is machine-independent (per-system lock
 * entries cover `x86_64-linux`, which is every tau machine), so it benefits new
 * machines too.
 *
 * This ONLY applies when the devbox.json being installed is the exact pristine
 * role render — a user-customized devbox.json never reads or writes the cache,
 * since its resolution isn't guaranteed to match the pristine set's.
 *
 * There is no time-based or content-based invalidation beyond the hash itself:
 * once a lock is cached, `@latest` is FROZEN at whatever Nixhub resolved at
 * first-cache time until the comfort set's content changes (a deliberate
 * determinism trade — every box gets the identical resolution, not whatever
 * Nixhub happens to answer today). To force a refresh (e.g. to pick up newer
 * package versions) without changing the comfort set, manually delete the
 * `devbox_lock_cache` row for the affected hash.
 */

